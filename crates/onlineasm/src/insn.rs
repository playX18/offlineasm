use crate::{Assembler, IntoOperand, Op};

macro_rules! mnemonic_methods {
    // The doc for one typed method is an `Emit` line plus the mnemonic's
    // reference entry, rendered by the build script into
    // `OUT_DIR/method-docs/<mnemonic>.md`. The empty doc between them keeps
    // the two as separate paragraphs.
    (@fixed $name:ident, $mn:literal) => {
        #[doc = concat!("Emit `", $mn, "`.")]
        #[doc = ""]
        #[doc = include_str!(concat!(env!("OUT_DIR"), "/method-docs/", $mn, ".md"))]
        pub fn $name(&mut self) -> &mut Self {
            self.emit_checked(crate::mnem::$name, &[]);
            self
        }
    };
    (@fixed $name:ident, $mn:literal, $($arg:ident),+) => {
        #[doc = concat!("Emit `", $mn, "` (widest operand form).")]
        #[doc = ""]
        #[doc = include_str!(concat!(env!("OUT_DIR"), "/method-docs/", $mn, ".md"))]
        pub fn $name(&mut self, $($arg: impl IntoOperand),+) -> &mut Self {
            let ops = [$(self.op($arg)),+];
            self.emit_checked(crate::mnem::$name, &ops);
            self
        }
    };
    ($(@fixed $name:ident, $mn:literal $(, $arg:ident)*;)*
     $(@variadic $vname:ident, $vmn:literal;)*) => {
        #[allow(non_snake_case)]
        impl<const BACKWARD: bool> Assembler<BACKWARD> {
            $( mnemonic_methods!(@fixed $name, $mn $(, $arg)*); )*

            $(#[doc = concat!("Emit `", $vmn, "` with a variable number of operands.")]
            #[doc = ""]
            #[doc = include_str!(concat!(env!("OUT_DIR"), "/method-docs/", $vmn, ".md"))]
            pub fn $vname(&mut self, ops: &[impl IntoOperand + Copy]) -> &mut Self {
                let resolved: Vec<Op> = ops.iter().map(|o| o.into_operand(self)).collect();
                self.emit_checked(crate::mnem::$vname, &resolved);
                self
            })*
        }


    };
}

